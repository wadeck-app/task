import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { initProject } from './initProject.js';
import { listRegisteredProjects, projectsRegistryPath } from './projectsRegistry.js';

describe('initProject', () => {
	let root: string;
	let configDir: string;
	let dir: string;

	beforeEach(() => {
		root = fs.mkdtempSync(path.join(os.tmpdir(), 'task-init-'));
		configDir = path.join(root, 'config');
		dir = path.join(root, 'proj');
		fs.mkdirSync(dir);
	});

	afterEach(() => {
		fs.rmSync(root, { recursive: true, force: true });
	});

	it('creates .task/tasks and a config.yml from the template, then registers the project', () => {
		const result = initProject(dir, configDir);
		expect(result).toEqual({
			taskDir: path.join(dir, '.task'),
			created: true,
			registration: { ok: true, added: true },
		});
		expect(fs.statSync(path.join(dir, '.task', 'tasks')).isDirectory()).toBe(true);
		const config = fs.readFileSync(path.join(dir, '.task', 'config.yml'), 'utf8');
		expect(config).toContain('# Generated by: task init');
		expect(config).toContain('  - name: done\n    terminal: true');
		expect(listRegisteredProjects(configDir)).toEqual([dir]);
	});

	it('is idempotent: an initialized project is left untouched and only registered', () => {
		fs.mkdirSync(path.join(dir, '.task', 'tasks'), { recursive: true });
		fs.writeFileSync(path.join(dir, '.task', 'config.yml'), 'statuses: [a]\n');
		const result = initProject(dir, configDir);
		expect(result.created).toBe(false);
		expect(result.registration).toEqual({ ok: true, added: true });
		expect(fs.readFileSync(path.join(dir, '.task', 'config.yml'), 'utf8')).toBe('statuses: [a]\n');
		expect(initProject(dir, configDir).registration).toEqual({ ok: true, added: false });
		expect(listRegisteredProjects(configDir)).toEqual([dir]);
	});

	it('creates missing parent directories, as `task init` always did', () => {
		const deep = path.join(root, 'a', 'b');
		expect(initProject(deep, configDir).created).toBe(true);
		expect(fs.existsSync(path.join(deep, '.task', 'config.yml'))).toBe(true);
	});

	it('never fails on a registry problem: the project is initialized and the failure is returned with its hint', () => {
		fs.mkdirSync(configDir, { recursive: true });
		fs.writeFileSync(projectsRegistryPath(configDir), '{not json');
		const result = initProject(dir, configDir);
		expect(result.created).toBe(true);
		expect(fs.existsSync(path.join(dir, '.task', 'config.yml'))).toBe(true);
		expect(result.registration.ok).toBe(false);
		if (!result.registration.ok) {
			expect(result.registration.message).toContain(projectsRegistryPath(configDir));
			expect(result.registration.hint).toMatch(/Fix or delete/);
		}
		expect(fs.readFileSync(projectsRegistryPath(configDir), 'utf8')).toBe('{not json');
	});
});
