function levenshtein(a: string, b: string): number {
	const m = a.length;
	const n = b.length;
	const dp: number[][] = Array.from({ length: m + 1 }, (_, i) =>
		Array.from({ length: n + 1 }, (_, j) => (i === 0 ? j : j === 0 ? i : 0))
	);
	for (let i = 1; i <= m; i++) {
		for (let j = 1; j <= n; j++) {
			dp[i]![j] =
				a[i - 1] === b[j - 1]
					? dp[i - 1]![j - 1]!
					: 1 + Math.min(dp[i - 1]![j]!, dp[i]![j - 1]!, dp[i - 1]![j - 1]!);
		}
	}
	return dp[m]![n]!;
}

/**
 * Matches a glob pattern (supporting * as wildcard) against a value.
 * The match is case-sensitive and anchored (full value must match).
 */
function matchGlob(pattern: string, value: string): boolean {
	// Escape all regex metacharacters except *, then replace * with .*
	const regexStr = pattern.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*');
	return new RegExp(`^${regexStr}$`).test(value);
}

function suggest(input: string, candidates: string[]): string | undefined {
	let best: string | undefined;
	let bestDist = Infinity;
	for (const c of candidates) {
		const d = levenshtein(input.toLowerCase(), c.toLowerCase());
		if (d < bestDist) {
			bestDist = d;
			best = c;
		}
	}
	return bestDist <= 3 ? best : undefined;
}

// Lazily resolved path to queue's JS entry point -- avoids shell and quoting issues.
let _queueJsPath: string | undefined;
function resolveQueueJsPath(): string {
	if (_queueJsPath) return _queueJsPath;
	// On Windows, use 'where queue.cmd' via shell to get a native Windows path.
	// On Unix, use 'which queue' to get the script path.
	let nativeDir: string;
	if (process.platform === 'win32') {
		const winPath = execSync('where queue.cmd', { encoding: 'utf8', windowsHide: true })
			.trim()
			.split('\n')[0]!
			.trim();
		nativeDir = path.dirname(winPath);
	} else {
		nativeDir = path.dirname(execFileSync('which', ['queue'], { encoding: 'utf8', windowsHide: true }).trim());
	}
	_queueJsPath = path.join(nativeDir, 'node_modules', '@wadeck-app', 'queue-cli', 'bin', 'queue.js');
	return _queueJsPath;
}

async function pushToQueue(event: string, payload: Record<string, unknown>): Promise<void> {
	const json = JSON.stringify(payload);
	let queueJs: string;
	try {
		queueJs = resolveQueueJsPath();
	} catch {
		process.stderr.write(`[task] queue not found on PATH -- event '${event}' not delivered\n`);
		return;
	}
	// Spawn node directly with queue.js -- no shell, args passed verbatim (no JSON quoting issues).
	await new Promise<void>(resolve => {
		const child = spawn(process.execPath, [queueJs, 'push', event, json], { stdio: 'inherit', windowsHide: true });
		child.on('close', code => {
			if (code !== 0) {
				process.stderr.write(`[task] queue push '${event}' failed (exit ${code}) -- event not delivered\n`);
			}
			resolve();
		});
		child.on('error', err => {
			process.stderr.write(`[task] queue push '${event}' error: ${(err as Error).message}\n`);
			resolve();
		});
	});
}

const FOLLOW_POLL_INTERVAL_MS = 500;

/** `task list --follow`: polls the task index and prints newly-created or status-changed tasks. */
async function runTaskListFollow(store: TaskStore, showAll: boolean, terminalStatuses: string[]): Promise<void> {
	const passesFilter = (t: TaskSummary) => showAll || !terminalStatuses.includes(t.status);
	const initialAll = store.list();
	for (const task of initialAll.filter(passesFilter)) {
		process.stdout.write(JSON.stringify(task) + '\n');
	}
	let snapshot = diffSnapshot(new Map(), initialAll, t => t.id).snapshot;

	process.stderr.write('[task] Following task list -- Ctrl+C to stop\n');
	await new Promise<void>(resolve => {
		const interval = setInterval(() => {
			const { changed, snapshot: next } = diffSnapshot(snapshot, store.list(), t => t.id);
			snapshot = next;
			for (const task of changed.filter(passesFilter)) {
				process.stdout.write(JSON.stringify(task) + '\n');
			}
		}, FOLLOW_POLL_INTERVAL_MS);
		process.on('SIGINT', () => {
			clearInterval(interval);
			resolve();
		});
	});
}

/** `task history <id> --follow`: polls one task's history array and prints newly-appended entries. */
async function runTaskHistoryFollow(store: TaskStore, taskId: string, initial: TaskRecord['history']): Promise<void> {
	for (const entry of initial) {
		process.stdout.write(JSON.stringify(entry) + '\n');
	}
	let count = initial.length;

	process.stderr.write(`[task] Following history of ${taskId} -- Ctrl+C to stop\n`);
	await new Promise<void>(resolve => {
		const interval = setInterval(() => {
			const { changed, count: nextCount } = diffAppendOnlyLog(count, store.get(taskId).history);
			count = nextCount;
			for (const entry of changed) {
				process.stdout.write(JSON.stringify(entry) + '\n');
			}
		}, FOLLOW_POLL_INTERVAL_MS);
		process.on('SIGINT', () => {
			clearInterval(interval);
			resolve();
		});
	});
}

function parseArgs(args: string[]): {
	configDir: string | undefined;
	projectDir: string | undefined;
	jsonMode: boolean;
	command: string | undefined;
	rest: string[];
} {
	let i = 0;
	let configDir: string | undefined;
	let projectDir: string | undefined;
	let jsonMode = false;

	while (i < args.length) {
		if (args[i] === '--config' && args[i + 1] !== undefined) {
			configDir = args[i + 1]!;
			i += 2;
		} else if (args[i] === '--json') {
			jsonMode = true;
			i++;
		} else {
			break;
		}
	}

	const command = args[i];
	const trailing = args.slice(i + 1);

	// Filter --project-dir <path> and --json from rest args
	const rest: string[] = [];
	for (let j = 0; j < trailing.length; j++) {
		if (trailing[j] === '--project-dir' && trailing[j + 1] !== undefined) {
			projectDir = trailing[j + 1]!;
			j++;
		} else if (trailing[j] === '--json') {
			jsonMode = true;
		} else {
			rest.push(trailing[j]!);
		}
	}

	return { configDir, projectDir, jsonMode, command, rest };
}

export interface CommandResult {
	exitCode: number;
	output: string;
}

function errorOutput(jsonMode: boolean, message: string, hint?: string): CommandResult {
	if (jsonMode) {
		return { exitCode: 1, output: JSON.stringify({ error: message }) };
	}
	const lines = [`Error: ${message}`];
	if (hint) lines.push(hint);
	return { exitCode: 1, output: lines.join('\n') };
}

export async function runTaskCommand(args: string[], cwd: string): Promise<CommandResult> {
	const { configDir: configDirArg, projectDir: projectDirArg, jsonMode, command, rest } = parseArgs(args);
	const effectiveProjectDir = projectDirArg ?? process.env['TASK_PROJECT_DIR'] ?? process.env['PROJECT_DIR'];
	const effectiveCwd = effectiveProjectDir ? path.resolve(cwd, effectiveProjectDir) : cwd;

	// Log every CLI invocation to ~/.config/task/logs/YYYY-MM-DD.ndjson
	try {
		logCliInvocation(ConfigDir.get('task'), 'task', args);
	} catch {
		/* never block the CLI on logging failure */
	}

	// Show update notice from a previous background update run
	const updateManager = new UpdateManager('@wadeck-app/task-cli');
	const updateState = updateManager.readAndClearState();
	if (updateState?.status === 'success') {
		process.stderr.write(`[task] Updated to v${updateState.targetVersion ?? updateState.newVersion}\n`);
	}
	if (updateState?.status === 'rolled-back') {
		process.stderr.write(
			`[task] Update to v${updateState.targetVersion} failed (self-check failed). Rolled back to v${updateState.previousVersion}. Run: task cli update --log\n`
		);
	}
	if (updateState?.status === 'failed') {
		process.stderr.write(
			`[task] Background update failed (${updateState.error ?? updateState.reason}). Run: task cli update\n`
		);
	}

	if (!command || command === '--help') {
		return {
			exitCode: 0,
			output: `task ${VERSION} - task tracker CLI

Concepts:
  task        A work item with id, description, status, type, labels, and metadata
  parent      Optional parentId on a task; hierarchy depth is unlimited (delete a parent: children become roots, or --cascade-delete)
  config      Project config at .task/config.yml (defines valid statuses; default: backlog, in-progress, done)
  init        Creates .task/ directory and config.yml in the current working directory
  id          Short prefix of the task UUID - any unambiguous prefix is accepted

Usage:
  task init                                  Initialize task project in current directory
  task new <description> [--parent <id>]     Create a new task (optionally under a parent); prints full task JSON
  task list [--json] [--all] [--follow|-f]   List tasks as JSON array (hides terminal statuses unless --all)
  task list --parent <id>                    List only the direct children of a task
  task list --tree                           List tasks as a nested forest (kept: matching tasks + the ancestors leading to them)
  task show <id> [--json] [--with-parent] [--with-children]   Show task detail (always incl. parentId, childrenIds); flags add parent/children summaries
  task history <id> [--json] [--follow|-f]   Show status-change history for a task
  task set-status <id> <status>              Update task status (valid values from .task/config.yml)
  task set-type <id> <type>                  Update task type (validated if types configured)
  task type list                             List valid types for this project
  task type add <name>                       Add a valid type
  task type remove <name>                    Remove a valid type
  task set-parent <id> <parent-id>           Attach a task under a parent (cycles are rejected)
  task remove-parent <id>                    Detach a task from its parent (it becomes a root task)
  task children <id> [--recursive]           List direct children (--recursive: nested subtree, any depth)
  task parents <id>                          List all ancestors, from the direct parent up to the root
  task tree <id>                             Complete tree containing the task (from its topmost ancestor); the task is flagged "selected"
  task add-label <id> <label>               Add a label to a task
  task remove-label <id> <label>            Remove a label from a task
  task set-meta <id> <key> <value>          Set a metadata key/value on a task
  task delete <id>[,<id2>,...]              Delete task(s) by ID (comma-separated)
  task delete --all                          Delete all tasks
  task delete --filter <field>=<value>       Delete tasks matching a filter (fields: id, title, status, parentId; glob * allowed)
  task delete --dry-run ...                  Show what would be deleted without deleting
  task delete ... --cascade-delete           Also delete all descendants of the matched tasks (default: children become root tasks)
  task plugins list [--json]                 List available built-in flow plugins
  task plugins config <id> [--json]         Show config snippet for a plugin
  task cli self-check                        Validate installation
  task cli update [--check] [--log]         Update to latest version
  task cli logs [--follow]                   Print today's invocation log

Global flags:
  --config <dir>       Global config directory (default: ~/.task)
  --json               Force JSON output; errors become {"error":"..."}
  --project-dir <dir>  Override project directory (also: TASK_PROJECT_DIR env var)

Output: all commands output JSON (tasks are JSON objects with id, description, status, type, labels, meta)

Exit codes:
  0  success
  1  error

Environment variables:
  TASK_CONFIG       Override global config directory (default: ~/.task)
  TASK_PROJECT_DIR  Override project directory`,
		};
	}

	if (command === '--version' || command === '-V') {
		return { exitCode: 0, output: VERSION };
	}

	if (command === 'init') {
		const taskDir = path.join(effectiveCwd, '.task');
		if (fs.existsSync(taskDir)) {
			return { exitCode: 0, output: 'Project already initialized.' };
		}
		fs.mkdirSync(path.join(taskDir, 'tasks'), { recursive: true });
		fs.writeFileSync(path.join(taskDir, 'config.yml'), PROJECT_CONFIG_TEMPLATE, 'utf8');
		return { exitCode: 0, output: `Initialized task project in ${taskDir}` };
	}

	if (command === 'cli') {
		const subCmd = rest[0];
		switch (subCmd) {
			case 'version':
				await runTaskCliVersion();
				return { exitCode: 0, output: '' };
			case 'update': {
				const hasCheck = rest.includes('--check');
				const hasLog = rest.includes('--log');
				await runTaskCliUpdate({ check: hasCheck, log: hasLog, rawArgs: rest });
				return { exitCode: 0, output: '' };
			}
			case 'rollback':
				await runTaskCliRollback();
				return { exitCode: 0, output: '' };
			case 'self-check':
				await runTaskCliSelfCheck();
				return { exitCode: 0, output: '' };
			case 'logs': {
				const follow = rest.includes('--follow');
				await runTaskCliLogs({ follow });
				return { exitCode: 0, output: '' };
			}
			case undefined:
			case '--help':
			case 'help':
				printTaskCliHelp();
				return { exitCode: 0, output: '' };
			// violations-suppress: ts/no-switch-default-break returns a user-facing error, not a silent fallback
			default:
				return errorOutput(
					jsonMode,
					`unknown task cli subcommand: ${subCmd}`,
					'Valid subcommands: version, update, rollback, self-check, logs'
				);
		}
	}

	if (command === 'plugins') {
		return runPluginsCommand(rest, jsonMode);
	}

	if (!TaskConfigLoader.isInitialized(effectiveCwd)) {
		return errorOutput(jsonMode, 'project not initialized', 'Run: task init');
	}

	let config: ReturnType<typeof TaskConfigLoader.load>;
	try {
		config = TaskConfigLoader.load({ configDir: configDirArg, projectDir: effectiveCwd });
	} catch (error) {
		return errorOutput(jsonMode, (error as Error).message);
	}
	const tasksDir = path.join(effectiveCwd, '.task', 'tasks');
	const store = new TaskStore(tasksDir);

	const projectEnv = {
		taskProjectName: path.basename(effectiveCwd),
		taskProjectPath: effectiveCwd,
	};

	switch (command) {
		case 'new': {
			const NEW_USAGE = 'Usage: task new <description> [--parent <id>]';
			let description: string | undefined;
			let parentArg: string | undefined;
			for (let i = 0; i < rest.length; i++) {
				const arg = rest[i]!;
				if (arg === '--parent') {
					parentArg = rest[i + 1];
					if (!parentArg) {
						return errorOutput(jsonMode, '--parent requires a task id', NEW_USAGE);
					}
					i++;
				} else if (arg.startsWith('--')) {
					return errorOutput(jsonMode, `unknown flag: ${arg}`, NEW_USAGE);
				} else if (description === undefined) {
					description = arg;
				}
			}
			if (!description) {
				return errorOutput(jsonMode, 'missing description', NEW_USAGE);
			}
			let task: TaskRecord;
			try {
				const parentId = parentArg === undefined ? undefined : store.findByPrefix(parentArg).id;
				task = store.create(description, config.defaultStatus, parentId);
			} catch (error) {
				return errorOutput(jsonMode, (error as Error).message);
			}
			await pushToQueue('onTaskCreated', {
				taskId: task.id,
				status: task.status,
				description: task.description,
				parentId: task.parentId,
				type: task.type,
				labels: task.labels ?? [],
				...projectEnv,
			});
			return { exitCode: 0, output: JSON.stringify(task, null, 2) };
		}

		case 'list': {
			const LIST_USAGE = 'Usage: task list [--all] [--parent <id>] [--tree] [--follow|-f]';
			let showAll = false;
			let follow = false;
			let tree = false;
			let parentArg: string | undefined;
			for (let i = 0; i < rest.length; i++) {
				const arg = rest[i]!;
				if (arg === '--all') {
					showAll = true;
				} else if (arg === '--follow' || arg === '-f') {
					follow = true;
				} else if (arg === '--tree') {
					tree = true;
				} else if (arg === '--parent') {
					parentArg = rest[i + 1];
					if (!parentArg) {
						return errorOutput(jsonMode, '--parent requires a task id', LIST_USAGE);
					}
					i++;
				} else if (arg.startsWith('-')) {
					return errorOutput(jsonMode, `unknown flag: ${arg}`, LIST_USAGE);
				}
			}
			if (follow && (tree || parentArg !== undefined)) {
				const conflicting = tree ? '--tree' : '--parent';
				return errorOutput(
					jsonMode,
					`--follow cannot be combined with ${conflicting}`,
					'--follow streams new/changed tasks as flat JSON lines; run the list again without --follow to see the hierarchy.'
				);
			}
			if (follow) {
				await runTaskListFollow(store, showAll, config.terminalStatuses);
				return { exitCode: 0, output: '' };
			}
			const passesFilter = (t: TaskSummary): boolean => showAll || !config.terminalStatuses.includes(t.status);
			try {
				const parentId = parentArg === undefined ? undefined : store.findByPrefix(parentArg).id;
				if (tree) {
					return {
						exitCode: 0,
						output: JSON.stringify(store.getForest({ parentId, predicate: passesFilter }), null, 2),
					};
				}
				const tasks = (parentId === undefined ? store.list() : store.getChildren(parentId)).filter(
					passesFilter
				);
				return { exitCode: 0, output: JSON.stringify(tasks, null, 2) };
			} catch (error) {
				return errorOutput(jsonMode, (error as Error).message);
			}
		}

		case 'show': {
			const SHOW_USAGE = 'Usage: task show <id> [--with-parent] [--with-children]';
			let id: string | undefined;
			let withParent = false;
			let withChildren = false;
			for (const arg of rest) {
				if (arg === '--with-parent') {
					withParent = true;
				} else if (arg === '--with-children') {
					withChildren = true;
				} else if (arg.startsWith('--')) {
					return errorOutput(jsonMode, `unknown flag: ${arg}`, 'Valid flags: --with-parent, --with-children');
				} else if (id === undefined) {
					id = arg;
				}
			}
			if (!id) {
				return errorOutput(jsonMode, 'missing id', SHOW_USAGE);
			}
			try {
				const task = store.findByPrefix(id);
				const children = store.getChildren(task.id);
				const detail: Record<string, unknown> = { ...task, childrenIds: children.map(c => c.id) };
				if (withParent) {
					const parent = task.parentId === undefined ? null : store.list().find(t => t.id === task.parentId);
					if (parent === undefined) {
						return errorOutput(
							jsonMode,
							`parent "${task.parentId}" of task "${task.id}" does not exist`,
							`Fix with: task remove-parent ${task.id}`
						);
					}
					detail['parent'] = parent;
				}
				if (withChildren) {
					detail['children'] = children;
				}
				return { exitCode: 0, output: JSON.stringify(detail, null, 2) };
			} catch (error) {
				return errorOutput(jsonMode, (error as Error).message);
			}
		}

		case 'history': {
			const id = rest[0];
			if (!id) {
				return errorOutput(jsonMode, 'missing id', 'Usage: task history <id> [--follow|-f]');
			}
			let task: TaskRecord;
			try {
				task = store.findByPrefix(id);
			} catch (error) {
				return errorOutput(jsonMode, (error as Error).message);
			}
			if (rest.includes('--follow') || rest.includes('-f')) {
				await runTaskHistoryFollow(store, task.id, task.history);
				return { exitCode: 0, output: '' };
			}
			return { exitCode: 0, output: JSON.stringify(task.history, null, 2) };
		}

		case 'set-status': {
			const id = rest[0];
			const statusArg = rest[1];
			if (!id || !statusArg) {
				return errorOutput(jsonMode, 'missing arguments', 'Usage: task set-status <id> <status>');
			}
			if (!config.statuses.includes(statusArg)) {
				const hint = suggest(statusArg, config.statuses);
				const validLine = `Valid statuses: ${config.statuses.join(', ')}`;
				const hintLine = hint ? `\nDid you mean: ${hint}?` : '';
				if (jsonMode) {
					return {
						exitCode: 1,
						output: JSON.stringify({
							error: `Invalid status: ${statusArg}. Valid values: ${config.statuses.join(', ')}`,
						}),
					};
				}
				return {
					exitCode: 1,
					output: `Error: unknown status "${statusArg}"\n${validLine}${hintLine}`,
				};
			}
			try {
				const before = store.findByPrefix(id);
				const updated = store.updateStatus(before.id, statusArg, before);
				await pushToQueue('onStatusChange', {
					taskId: updated.id,
					oldStatus: before.status,
					newStatus: updated.status,
					type: updated.type,
					labels: updated.labels ?? [],
					...projectEnv,
				});
				return { exitCode: 0, output: JSON.stringify(updated, null, 2) };
			} catch (error) {
				return errorOutput(jsonMode, (error as Error).message);
			}
		}

		case 'set-type': {
			const id = rest[0];
			const type = rest[1];
			if (!id || !type) {
				return errorOutput(jsonMode, 'missing arguments', 'Usage: task set-type <id> <type>');
			}
			const typeStrategy = resolveTypeValidationStrategy(config.types);
			const typeValidation = typeStrategy.validate(type);
			if (!typeValidation.valid) {
				return errorOutput(jsonMode, typeValidation.error);
			}
			try {
				const updated = store.setType(store.findByPrefix(id).id, type);
				return { exitCode: 0, output: JSON.stringify(updated, null, 2) };
			} catch (error) {
				return errorOutput(jsonMode, (error as Error).message);
			}
		}

		case 'add-label': {
			const id = rest[0];
			const label = rest[1];
			if (!id || !label) {
				return errorOutput(jsonMode, 'missing arguments', 'Usage: task add-label <id> <label>');
			}
			try {
				const updated = store.addLabel(store.findByPrefix(id).id, label);
				return { exitCode: 0, output: JSON.stringify(updated, null, 2) };
			} catch (error) {
				return errorOutput(jsonMode, (error as Error).message);
			}
		}

		case 'remove-label': {
			const id = rest[0];
			const label = rest[1];
			if (!id || !label) {
				return errorOutput(jsonMode, 'missing arguments', 'Usage: task remove-label <id> <label>');
			}
			try {
				const updated = store.removeLabel(store.findByPrefix(id).id, label);
				return { exitCode: 0, output: JSON.stringify(updated, null, 2) };
			} catch (error) {
				return errorOutput(jsonMode, (error as Error).message);
			}
		}

		case 'set-parent': {
			const id = rest[0];
			const parentArg = rest[1];
			if (!id || !parentArg) {
				return errorOutput(jsonMode, 'missing arguments', 'Usage: task set-parent <id> <parent-id>');
			}
			try {
				const updated = store.setParent(store.findByPrefix(id).id, store.findByPrefix(parentArg).id);
				return { exitCode: 0, output: JSON.stringify(updated, null, 2) };
			} catch (error) {
				return errorOutput(jsonMode, (error as Error).message);
			}
		}

		case 'remove-parent': {
			const id = rest[0];
			if (!id) {
				return errorOutput(jsonMode, 'missing id', 'Usage: task remove-parent <id>');
			}
			try {
				const updated = store.removeParent(store.findByPrefix(id).id);
				return { exitCode: 0, output: JSON.stringify(updated, null, 2) };
			} catch (error) {
				return errorOutput(jsonMode, (error as Error).message);
			}
		}

		case 'children': {
			const id = rest[0];
			if (!id) {
				return errorOutput(jsonMode, 'missing id', 'Usage: task children <id> [--recursive]');
			}
			try {
				const taskId = store.findByPrefix(id).id;
				const result = rest.includes('--recursive')
					? store.getTree(taskId).children
					: store.getChildren(taskId);
				return { exitCode: 0, output: JSON.stringify(result, null, 2) };
			} catch (error) {
				return errorOutput(jsonMode, (error as Error).message);
			}
		}

		case 'parents': {
			const id = rest[0];
			if (!id) {
				return errorOutput(jsonMode, 'missing id', 'Usage: task parents <id>');
			}
			try {
				const ancestors = store.getAncestors(store.findByPrefix(id).id);
				return { exitCode: 0, output: JSON.stringify(ancestors, null, 2) };
			} catch (error) {
				return errorOutput(jsonMode, (error as Error).message);
			}
		}

		case 'tree': {
			const id = rest[0];
			if (!id) {
				return errorOutput(jsonMode, 'missing id', 'Usage: task tree <id>');
			}
			try {
				const tree = store.getFullTree(store.findByPrefix(id).id);
				return { exitCode: 0, output: JSON.stringify(tree, null, 2) };
			} catch (error) {
				return errorOutput(jsonMode, (error as Error).message);
			}
		}

		case 'set-meta': {
			const id = rest[0];
			const key = rest[1];
			const value = rest[2];
			if (!id || !key || value === undefined) {
				return errorOutput(jsonMode, 'missing arguments', 'Usage: task set-meta <id> <key> <value>');
			}
			try {
				const updated = store.setMeta(store.findByPrefix(id).id, key, value);
				return { exitCode: 0, output: JSON.stringify(updated, null, 2) };
			} catch (error) {
				return errorOutput(jsonMode, (error as Error).message);
			}
		}

		case 'delete': {
			// Parse flags and positional args
			let dryRun = false;
			let hasAll = false;
			// Like SQL's ON DELETE CASCADE: also delete every descendant (default: children become root tasks).
			let cascade = false;
			let filterSpec: string | undefined;
			const positionalIds: string[] = [];

			let i = 0;
			while (i < rest.length) {
				const arg = rest[i]!;
				if (arg === '--dry-run') {
					dryRun = true;
					i++;
				} else if (arg === '--all') {
					hasAll = true;
					i++;
				} else if (arg === '--cascade-delete') {
					cascade = true;
					i++;
				} else if (arg === '--filter') {
					filterSpec = rest[i + 1];
					i += 2;
				} else if (arg.startsWith('--')) {
					return errorOutput(
						jsonMode,
						`unknown flag: ${arg}`,
						'Valid flags: --all, --filter <field>=<value>, --dry-run, --cascade-delete'
					);
				} else {
					// Comma-separated IDs allowed in a single positional arg
					positionalIds.push(...arg.split(',').filter(s => s.length > 0));
					i++;
				}
			}

			// Error: --all and --filter both specified
			if (hasAll && filterSpec !== undefined) {
				return errorOutput(jsonMode, '--all and --filter cannot be combined');
			}

			// Error: positional IDs combined with --all or --filter
			if (positionalIds.length > 0 && (hasAll || filterSpec !== undefined)) {
				return errorOutput(jsonMode, 'positional IDs cannot be combined with --all or --filter');
			}

			// No selector provided at all
			if (!hasAll && filterSpec === undefined && positionalIds.length === 0) {
				return errorOutput(
					jsonMode,
					'missing arguments',
					'Usage: task delete <id>[,<id2>,...] | --all | --filter <field>=<value>'
				);
			}

			const VALID_FILTER_FIELDS = ['id', 'title', 'status', 'parentId'] as const;
			type FilterableField = (typeof VALID_FILTER_FIELDS)[number];

			let tasksToDelete: TaskSummary[] = [];
			const warnings: string[] = [];

			if (hasAll) {
				tasksToDelete = store.list();
			} else if (filterSpec !== undefined) {
				const eqIdx = filterSpec.indexOf('=');
				if (eqIdx === -1) {
					return errorOutput(
						jsonMode,
						`invalid filter: "${filterSpec}" (expected field=value)`,
						`Valid fields: ${VALID_FILTER_FIELDS.join(', ')}`
					);
				}
				const field = filterSpec.slice(0, eqIdx) as FilterableField;
				const valuesStr = filterSpec.slice(eqIdx + 1);
				const values = valuesStr.split(',').filter(v => v.length > 0);

				if (!(VALID_FILTER_FIELDS as ReadonlyArray<string>).includes(field)) {
					return errorOutput(
						jsonMode,
						`unknown filter field: "${field}"`,
						`Valid fields: ${VALID_FILTER_FIELDS.join(', ')}`
					);
				}

				const all = store.list();
				// A root task has no parentId: it never matches a parentId pattern.
				tasksToDelete = all.filter(t => t[field] !== undefined && values.some(v => matchGlob(v, t[field]!)));
			} else {
				// Positional IDs: resolve by prefix
				const all = store.list();
				for (const rawId of positionalIds) {
					const matches = all.filter(t => t.id.startsWith(rawId));
					if (matches.length === 0) {
						warnings.push(`Warning: task not found: ${rawId}`);
					} else if (matches.length > 1) {
						return errorOutput(
							jsonMode,
							`ambiguous prefix "${rawId}" matches: ${matches.map(t => t.id).join(', ')}`
						);
					} else {
						tasksToDelete.push(matches[0]!);
					}
				}
				// Print warnings to stderr (warn but continue)
				for (const w of warnings) {
					process.stderr.write(w + '\n');
				}
			}

			if (tasksToDelete.length === 0) {
				return { exitCode: 0, output: 'Nothing to delete.' };
			}

			if (cascade) {
				const selected = new Set(tasksToDelete.map(t => t.id));
				for (const t of [...tasksToDelete]) {
					for (const descendant of store.getDescendants(t.id)) {
						if (!selected.has(descendant.id)) {
							selected.add(descendant.id);
							tasksToDelete.push(descendant);
						}
					}
				}
			}

			// Children that survive the deletion lose their parent and become root tasks.
			const deletedIds = new Set(tasksToDelete.map(t => t.id));
			const orphanCount = store
				.list()
				.filter(t => t.parentId !== undefined && deletedIds.has(t.parentId) && !deletedIds.has(t.id)).length;

			if (dryRun) {
				const lines = ['Would delete:'];
				for (const t of tasksToDelete) {
					lines.push(`  ${t.id}  ${t.title}  [${t.status}]`);
				}
				lines.push(`Total: ${tasksToDelete.length} task(s).`);
				if (orphanCount > 0) {
					lines.push(`${orphanCount} child task(s) would become root tasks (their parent is deleted).`);
				}
				return { exitCode: 0, output: lines.join('\n') };
			}

			let deletedCount = 0;
			for (const t of tasksToDelete) {
				if (store.deleteTask(t.id)) {
					deletedCount++;
				}
			}

			const orphanNote =
				orphanCount > 0 ? `\n${orphanCount} child task(s) became root tasks (their parent was deleted).` : '';
			return { exitCode: 0, output: `Deleted ${deletedCount} task(s).${orphanNote}` };
		}

		case 'type': {
			const subCmd = rest[0];
			if (!subCmd || subCmd === '--help') {
				return {
					exitCode: 0,
					output: `task type - manage valid task types for this project

Usage:
  task type list              List valid types configured for this project
  task type add <name>        Add a valid type
  task type remove <name>     Remove a valid type
  task type --help            Show this help

Types are stored in .task/config.yml under the 'types' key.
When types are configured, 'task set-type' validates against this list.
When no types are configured, any string is accepted (backwards compatible).`,
				};
			}
			switch (subCmd) {
				case 'list': {
					if (config.types.length === 0) {
						return { exitCode: 0, output: '(no types configured -- any string is accepted)' };
					}
					return { exitCode: 0, output: config.types.join('\n') };
				}
				case 'add': {
					const typeName = rest[1];
					if (!typeName) {
						return errorOutput(jsonMode, 'missing type name', 'Usage: task type add <name>');
					}
					TaskConfigLoader.addType(effectiveCwd, typeName);
					return { exitCode: 0, output: `Added type: ${typeName}` };
				}
				case 'remove': {
					const typeName = rest[1];
					if (!typeName) {
						return errorOutput(jsonMode, 'missing type name', 'Usage: task type remove <name>');
					}
					TaskConfigLoader.removeType(effectiveCwd, typeName);
					return { exitCode: 0, output: `Removed type: ${typeName}` };
				}
				// violations-suppress: ts/no-switch-default-break returns a user-facing error, not a silent fallback
				default:
					return errorOutput(
						jsonMode,
						`unknown task type subcommand: ${subCmd}`,
						'Valid subcommands: list, add, remove'
					);
			}
		}

		// violations-suppress: ts/no-switch-default-break returns a user-facing error, not a silent fallback
		default:
			return errorOutput(
				jsonMode,
				`unknown command: ${command}`,
				'Valid commands: init, new, list, show, history, set-status, set-type, set-parent, remove-parent, children, parents, tree, add-label, remove-label, set-meta, delete, type, plugins'
			);
	}
}

async function main(): Promise<void> {
	const args = process.argv.slice(2);
	const { exitCode, output } = await runTaskCommand(args, process.cwd());
	if (exitCode === 0) {
		if (output.length > 0) process.stdout.write(output + '\n');
	} else {
		if (output.length > 0) process.stderr.write(output + '\n');
	}

	// Schedule background updater after command completes
	const bundlePath = resolveOwnBundlePath(TASK_BUNDLE_NAME, fileURLToPath(import.meta.url));
	new UpdateManager('@wadeck-app/task-cli').scheduleBackgroundUpdate(bundlePath, 'task-updater.cjs');

	process.exit(exitCode);
}

const isEntryPoint =
	process.argv[1] !== undefined &&
	(process.argv[1] === fileURLToPath(import.meta.url) ||
		process.argv[1].endsWith('TaskIndex.js') ||
		process.argv[1].endsWith('TaskIndex.ts'));

if (isEntryPoint) {
	main().catch(error => {
		process.stderr.write(`Error: ${String(error)}\n`);
		process.exit(1);
	});
}
