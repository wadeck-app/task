// What a backend can do, declared once and tested by the contract suite (contract/backendContract.ts).
// Enum-valued where the difference matters (design 1.3); a value is a promise the contract checks.
import type { LinkType } from '../TaskStore.js';

export type BackendKind = 'local' | 'github' | 'gitlab' | 'remote';

/** Every backend kind of the design, as a runtime list (config validation lists them; only the installed ones can be opened). */
export const BACKEND_KINDS: readonly BackendKind[] = Object.freeze(['local', 'github', 'gitlab', 'remote'] as const);

/** Parent/child tasks: any depth, a depth cap (GitHub sub-issues), or none. */
export type HierarchySupport = 'unlimited' | 'limited' | 'none';
/** Statuses: any configured name, a configured mapping onto the system's own, or only open/closed. */
export type StatusSupport = 'free' | 'mapped' | 'open-closed';
/** Status history: written by task, rebuilt from the system's events, or absent. */
export type HistorySupport = 'stored' | 'derived' | 'none';
/** Non-status changes (type, labels, meta, links, parent, title...): written by task, read from the system, or absent. */
export type ActivitySupport = 'stored' | 'native' | 'none';
/** Removing a task: really removed, only closed, or refused. */
export type DeleteSupport = 'yes' | 'close-only' | 'no';
/** Title search: over the local index, by the system, or not offered. */
export type SearchSupport = 'index' | 'native' | 'none';
/** A write carrying `expectedRevision`: compared atomically, compared right before the write (residual race), or not offered. */
export type ConcurrencySupport = 'revision' | 'check-then-write' | 'none';
/** Changing tasks: every write works, or every write is refused (a read-only view of a system: `UnsupportedByBackendError` on each). */
export type WriteSupport = 'full' | 'none';
/** Task ids: generated by task (prefix lookup works) or assigned by the system (exact ids only). */
export type IdSupport = 'generated' | 'assigned';

export interface BackendCapabilities {
	hierarchy: HierarchySupport;
	/** The link types the backend stores; any other type is refused with UnsupportedByBackendError. */
	linkTypes: readonly LinkType[];
	status: StatusSupport;
	history: HistorySupport;
	activity: ActivitySupport;
	delete: DeleteSupport;
	search: SearchSupport;
	concurrency: ConcurrencySupport;
	ids: IdSupport;
	labels: boolean;
	meta: boolean;
	comments: boolean;
	/** Whether any write is accepted. `none`: reads only, each write throws UnsupportedByBackendError for this capability. */
	writes: WriteSupport;
	/** Parent and links are mirrored in the summaries of `list()` (graph and tree queries never read a task). */
	indexedGraph: boolean;
}

/** The local file store: everything, unlimited. The reference the other backends are compared to. */
export const LOCAL_CAPABILITIES: BackendCapabilities = Object.freeze({
	hierarchy: 'unlimited',
	linkTypes: Object.freeze(['blockedBy', 'duplicateOf', 'causedBy'] as const),
	status: 'free',
	history: 'stored',
	activity: 'stored',
	delete: 'yes',
	search: 'index',
	concurrency: 'revision',
	ids: 'generated',
	labels: true,
	meta: true,
	comments: true,
	writes: 'full',
	indexedGraph: true,
});

